#!/usr/bin/ruby
require "json"
require "fileutils"
require "erb"
require 'optparse'
require 'ostruct'

# Structure to hold configuration settings
options = OpenStruct.new(
	conf:    './softwares/.template_config.json',
	op:      false,  
	verbose: false,
	cockpitUserPassword: nil,
	cockpitUsername: nil,
	username: nil,
	combineMegazord: [],
	name: nil
)
opt_parser = OptionParser.new do |opts|
	opts.banner = "Usage: sudo ruby backup.rb --conf PATH -v --cockpit-user-password PASSWORD"
	opts.on("-c PATH", "--conf PATH", "Path to config file. (Default: ./softwares/.template_config.json)") do |path|
    	options.conf = path
	end
	opts.on("-n SERVERNAME", "--name SERVERNAME", "Server Name, sent via this param has highest priority. Second Priority is CONFIG['title']") do |path|
    	options.name = path
	end
	opts.on("-p STRING", "--cockpit-user-password STRING", "Password for a cockpit user, sent via this param has highest priority. Second Priority is CONFIG['cockpitUserPassword'], 'someRanDomPhraze834587' if empty in both places") do |p|
    	options.cockpitUserPassword = p
	end
	opts.on("-c STRING", "--cockpit-username STRING", "Username for a cockpit user, sent via this param has highest priority. Second Priority is CONFIG['cockpitUsername'], nil if empty in both places") do |p|
    	options.cockpitUsername = p
	end
	opts.on("-u STRING", "--username STRING", "Username for a ssh user, sent via this param has highest priority. Second Priority is CONFIG['username'], nil if empty in both places") do |p|
    	options.username = p
	end
	opts.on("-o", "--[no-]op", "Enable (--op) or disable (--no-op) actual files copying. (Default: --no-op)") do |o|
    	options.op = o
	end
	opts.on("-v", "--verbose", "Enable verbose output for files copying. (Default: false)") do
		options.verbose = true
	end
	opts.on("--combine-megazord SOFTWARES", "Enable JSON combining from softwares list, use file names from ./softwares/ folder, f.e.: --combine-megazord '1-network.json,3-nginx.json'. (Default: false)") do |s|
		options.combineMegazord = s.split(',').sort if !s.nil?
	end
	opts.on("-h", "--help", "Prints this help message.") do
		puts opts
		exit
	end
end
begin
	opt_parser.parse!(ARGV)
rescue OptionParser::InvalidOption => e
	puts e.message
	puts opt_parser
	exit(1)
end
# Layout related constants. Keep first symbol '#' to be sure restore.sh does not get some text uncommented
H2_PREFIX = "###"
H1_PREFIX = "#{H2_PREFIX}#{'--'*3}"
SECTIONS_SEPARATOR = "#{H2_PREFIX}#{'===' * 30}"

VERBOSE = options.verbose
NOOP = !options.op
START_TIME = Time.now.strftime("%Y-%m-%d_%H-%M-%S")
ROOT_PATH = File.expand_path(`pwd`.chomp)
if options.combineMegazord.empty?
	config = JSON.parse(File.read(File.expand_path(options.conf)))
	config_file_path = [File.expand_path(options.conf)]
else
	raise OptionParser::InvalidOption.new("You must set '--name SERVERNAME --username STRING --cockpit-user-password STRING --cockpit-username STRING' to use this mode") if options['name'].nil? || options['username'].nil? || options['cockpitUsername'].nil? || options['cockpitUserPassword'].nil?
	megazord = []
	options.combineMegazord.map { |e| megazord.push(content = JSON.parse(File.read(File.expand_path("./softwares/#{e}")))) } 
	config = {'softwares' => megazord}
	config_file_path = options.combineMegazord.map { |e| "./softwares/#{e}" }
end
CONFIG_PATH = config_file_path
# CONST assigned depending on priority Command-Line-Params -> JSON Config -> Local Defaults
TITLE = options['name'] || config['title'] || ""
BACKUP_PATH = File.join(ROOT_PATH,"#{TITLE}-#{START_TIME}")
COCKPIT_USERNAME = options.cockpitUsername || config["cockpitUsername"] || ""
COCKPIT_USER_PASSWORD = options.cockpitUserPassword || config["cockpitUserPassword"] || "someRanDomPhraze834587"
USERNAME = options.username || config["username"]

CONFIG = { #Resulting Config with all Constants
	"title" => TITLE,
	"megazordCombined?" => !options.combineMegazord.empty?,
	"username" => USERNAME,
	"cockpitUsername" => COCKPIT_USERNAME,
	"cockpitUserPassword" => COCKPIT_USER_PASSWORD,
	"softwares" => config["softwares"]
}
TAR_COMMAND = "tar -czf #{BACKUP_PATH}.tar.gz -C #{File.dirname(BACKUP_PATH)} #{File.basename(BACKUP_PATH)}"
ARCHIVE_NAME = "#{BACKUP_PATH}.tar.gz".split("/").last
UNTAR_COMMAND = "tar -xzvf /home/#{USERNAME}/#{ARCHIVE_NAME}"


RESTORE_SH_ERB = "#!/bin/bash
set -x
<%=SECTIONS_SEPARATOR%>
<%=H1_PREFIX%> This is an autogenerated restore script built on <%=CONFIG_PATH%> config
<%=H1_PREFIX%> Be sure it is being run as ROOT
<%=SECTIONS_SEPARATOR%>
<%=H1_PREFIX%> Stage1: Installing custom repos and packages
DEBIAN_FRONTEND=noninteractive apt update; apt upgrade
<%=@customAptRepoCommands.join('; ')%> 
apt install -y <%=@aptPackages.join(' ')%> 
<%=SECTIONS_SEPARATOR%>

<%=SECTIONS_SEPARATOR%>
<%=H1_PREFIX%> Stage 2: Setting up other pre-requisites <%=@preCommands.join('')%>
<%=SECTIONS_SEPARATOR%>

<%=SECTIONS_SEPARATOR%>
<%=H1_PREFIX%> Stage 3: Restoring backup files <%=@restoreCommands.join('')%>
<%=SECTIONS_SEPARATOR%>

<%=SECTIONS_SEPARATOR%>
<%=H1_PREFIX%> Stage 4: Restarting and enabling services <%=@postCommands.join('')%>
<%=SECTIONS_SEPARATOR%>

<%=SECTIONS_SEPARATOR%>
<%=H1_PREFIX%> !!! END OF RESTORE SCRIPT
<%=SECTIONS_SEPARATOR%>
"

HEADING = [
	SECTIONS_SEPARATOR,
	"#{H1_PREFIX} Backing up files",
	"#{H1_PREFIX} Script Configuration:",
	"#{H1_PREFIX}   * Combine Megazord Mode: #{!options.combineMegazord.empty?}",
	"#{H1_PREFIX}   * Config File(s) path: #{config_file_path}",
	"#{H1_PREFIX}   * Operational mode: #{!NOOP}",
	"#{H1_PREFIX}   * Verbose output: #{VERBOSE}",
	"#{H1_PREFIX}   * Backup root folder: #{BACKUP_PATH}",
	SECTIONS_SEPARATOR,
	"#{H1_PREFIX} Backup Configuration: ",
	"#{H1_PREFIX}   * Server Name: #{TITLE}",
	"#{H1_PREFIX}   * Softwares: #{CONFIG['softwares'].map { |e| e['name'] }}",
	"#{H1_PREFIX}   * SSH User: #{USERNAME}",
	"#{H1_PREFIX}   * Cockpit User: #{COCKPIT_USERNAME}",
	"#{H1_PREFIX}   * Cockpit User Password: #{COCKPIT_USER_PASSWORD}",
	SECTIONS_SEPARATOR,
	"#{H1_PREFIX} BACKING UP STARTED",
	SECTIONS_SEPARATOR
]
FOOTER = [
	"\n\n#{SECTIONS_SEPARATOR}",
	"#{H1_PREFIX} All needed files were archived. See below for hints on how to copy backup and restore it",
	"#{H2_PREFIX} scp command: to copy file FROM this server: ",
	"scp #{TITLE}:#{BACKUP_PATH}.tar.gz ~/Desktop",
	"#{SECTIONS_SEPARATOR}",
	"",
	"#{H1_PREFIX} To Retore:",
	"#{H2_PREFIX} copy file to this server",
	"scp ~/Desktop/#{ARCHIVE_NAME} #{TITLE}:/home/ubuntu/",
	"#{H2_PREFIX} untar command:",
	UNTAR_COMMAND,
	"#{H2_PREFIX} run restore script",
	"cd /home/ubuntu/#{TITLE}-#{START_TIME}/; sudo bash ./restore.sh",
	"#{SECTIONS_SEPARATOR}\n"
]
def gsubVarsGeneric(string)
	return string.gsub("$COCKPIT_USERNAME", COCKPIT_USERNAME)
		.gsub("$COCKPIT_USER_PASSWORD", COCKPIT_USER_PASSWORD)
		.gsub("$START_TIME", START_TIME)
		.gsub("$ROOT_PATH", ROOT_PATH)
		.gsub("$USERNAME", USERNAME)
		.gsub("$TITLE", TITLE)
end
def gsubVars(string)
	return gsubVarsGeneric(string).gsub("$BACKUP_PATH", BACKUP_PATH)
		
end
def gsubVarsRestore(string)
	return gsubVarsGeneric(string).gsub("$BACKUP_PATH", '.')
end
def doBackupCommandsAndPrepareRestoreCommands(confHash = {})
	puts HEADING.join("\n")
	@preCommands = []
	@restoreCommands = []
	@postCommands = []
	@customAptRepoCommands = []
	@aptPackages = []
	confHash["softwares"].each do |s|
		softwarePath = File.join(BACKUP_PATH, s['name'])
		FileUtils.mkdir_p(softwarePath, verbose: (VERBOSE || NOOP), noop: NOOP)
		s['backup'].each do |e|
			if e['type'] == "FILE" then
				categoryPath = File.join(softwarePath, e['name'])
				FileUtils.mkdir_p(categoryPath, verbose: (VERBOSE || NOOP), noop: NOOP)
				FileUtils.cp(gsubVars(e['path']),categoryPath , noop: NOOP ,verbose: (VERBOSE || NOOP))
				command = "cp -v ./#{s['name']}/#{e['name']}/#{e['path'].split("/").last} #{e['path']}"
				@restoreCommands.push("\n#{H2_PREFIX} #{e['name']}\n")
				@restoreCommands.push(command)
			elsif e["type"] == "DIR"
				pathUnlast = File.join(e['path'].split('/')[0..-1])
				FileUtils.cp_r(gsubVars(e['path']), softwarePath, verbose: (VERBOSE || NOOP), noop: NOOP)
				command = "cp -vr ./#{s['name']}/#{e['path'].split("/").last}/* #{gsubVars(pathUnlast)}"
				@restoreCommands.push("\n#{H2_PREFIX} #{e['name']}\n")
				@restoreCommands.push(command)
			elsif e["type"] == "COMMAND"
				puts gsubVars(e['path']) if NOOP
				system gsubVars(e['path']) if !NOOP
			end
		end
		@preCommands.concat(preparePrePostCommands(s['preRestore']))
		@postCommands.concat(preparePrePostCommands(s['postRestore']))
		@customAptRepoCommands.concat(s['customAptRepoCommands']) if s['customAptRepoCommands']
		@aptPackages.concat(s['aptPackages'])
	end
	puts "#{SECTIONS_SEPARATOR}"
	puts "#{H1_PREFIX} BACKING UP FINISHED"
	puts "#{H1_PREFIX} ACTUAL FILES COPYING WAS SKIPPED AS NOOP MODE ENABLED" if NOOP
	puts "#{SECTIONS_SEPARATOR}"
	content = ERB.new(RESTORE_SH_ERB)
	if !NOOP	
		puts "#{H1_PREFIX} Saving backup/restore script and config"
		system "echo #{CONFIG} > #{BACKUP_PATH}/#{TITLE}.json"
		FileUtils.cp(__FILE__, BACKUP_PATH,verbose: (VERBOSE || NOOP))
		File.open(File.join(BACKUP_PATH, 'restore.sh'), "w") do |file|
			file.puts(content.result(binding))
		end
		system "echo '#{JSON.pretty_generate(CONFIG)}' > #{BACKUP_PATH}/#{TITLE}.json"
		puts "#{H1_PREFIX} Archiving the backup"
		puts "#{H2_PREFIX} #{TAR_COMMAND}"
		system(TAR_COMMAND)
		puts "#{SECTIONS_SEPARATOR}"
	else
		puts "\n#{SECTIONS_SEPARATOR}"
		puts "#{H1_PREFIX} RESTORE SCRIPT BELOW"
		puts "#{SECTIONS_SEPARATOR}\n\n"
		system "echo '#{JSON.pretty_generate(CONFIG)}' > #{ROOT_PATH}/#{TITLE}.json"
		puts content.result(binding)
	end
	puts FOOTER.join("\n")
end
def preparePrePostCommands(preRestoreArray = [])
	return preRestoreArray.map { |e| "\n#{H2_PREFIX} #{e["name"]}\n#{gsubVarsRestore(e["command"])}" }
end
doBackupCommandsAndPrepareRestoreCommands(CONFIG)
